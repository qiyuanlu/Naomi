import Foundation
let size = CGSize(width: 112, height: 121.333333333)
let screen = CGRect(x: 0, y: 0, width: 1440, height: 900)
let bottom = Track(screen: screen, visible: CGRect(x: 0,y: 80,width: 1440,height: 795), size: size)
assert(abs(bottom.y - (80-size.height*5/208)) < 0.001)
assert(bottom.clamp(-1000) == 4 && bottom.clamp(2000) == 1324)
let left = Track(screen: screen, visible: CGRect(x: 90,y: 0,width: 1350,height: 875), size: size)
assert(left.minX == 94)
let hidden = Track(screen: screen, visible: CGRect(x: 0,y: 0,width: 1440,height: 875), size: size)
assert(hidden.y >= 0 && hidden.y < 4)
let secondary = Track(screen: CGRect(x: -1920,y: -200,width: 1920,height:1080), visible: CGRect(x:-1920,y:-200,width:1920,height:1055), size:size)
assert(secondary.minX == -1916 && secondary.maxX == -116)
assert(secondary.clamp(900) == -116)
let narrow = Track(screen: CGRect(x:0,y:0,width:60,height:300), visible:CGRect(x:0,y:0,width:60,height:280),size:size)
assert(narrow.maxX == narrow.minX)
print("PASS: bottom Dock, side Dock, hidden Dock, negative-coordinate display, clamping, narrow-screen bounds")

var pet = PetBehavior()
assert(pet.mood == .sitting)
pet.advance(119.9); assert(pet.mood == .sitting)
pet.advance(0.1); assert(pet.mood == .resting)
pet.advance(59.9); assert(pet.mood == .resting)
pet.advance(0.1); assert(pet.mood == .asleep)
pet.poke(leftHalf: true); assert(pet.mood == .runningRight && pet.unattended == 0)
pet.advance(0.9); assert(pet.mood == .runningRight)
pet.advance(0.2); assert(pet.mood == .sitting)
pet.poke(leftHalf: false); assert(pet.mood == .runningLeft)
pet.stopAtEdge(); assert(pet.mood == .sitting)
pet.advance(180); pet.settle(); assert(pet.mood == .sitting && pet.unattended == 0)
print("PASS: quiet start, 120-second rest, 180-second sleep, click directions, brief run, wake/reset, stop at edge")

assert(PetPresentation(mood: .resting, isCarried: false) == .lying)
assert(PetPresentation(mood: .asleep, isCarried: false) == .sleeping)
for mood: PetMood in [.sitting, .resting, .asleep, .runningLeft, .runningRight] {
    assert(PetPresentation(mood: mood, isCarried: true) == .carried)
}
assert(PetPresentation(mood: .sitting, isCarried: false) == .sprite)
print("PASS: side-lying rest/sleep, carried override in all states, release restores sitting")
